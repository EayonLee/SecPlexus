import { extraGeneratedFiles } from "./catalog-files.mjs";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const sharedPath = "src/packages/go/result/";
const codes = JSON.parse(readFileSync(`${sharedPath}error-codes.json`, "utf8"));
assert.equal(new Set(codes.map((entry) => entry.code)).size, codes.length, "Duplicate result codes");
const resultNames = new Set();
for (const entry of codes) {
  assert(!resultNames.has(entry.name), `Duplicate result export name ${entry.name}`);
  resultNames.add(entry.name);
  assert(entry.code === "ok" ? entry.status === 200 : entry.status >= 400 && entry.status <= 599);
  assert(entry.message && entry.module);
}
const outputs = new Map();
const write = (filename, content) => outputs.set(filename, content);
write(
  `${sharedPath}codes.gen.go`,
  `// Code generated by scripts/generate-catalogs.mjs. DO NOT EDIT.\npackage result\n\n// Code 是跨语言契约中的稳定结果码。\ntype Code string\n\n// Definition 记录结果码对应的 HTTP 状态与默认公开消息。\ntype Definition struct { Status int; Message string }\n\nconst (\n${codes.map((c) => `Code${c.name} Code = ${JSON.stringify(c.code)}`).join("\n")}\n)\n\n// Lookup 查询已注册结果码；未知码不会被当作成功。\nfunc Lookup(code Code) (Definition, bool) {\nswitch code {\n${codes.map((c) => `case Code${c.name}: return Definition{Status:${c.status},Message:${JSON.stringify(c.message)}},true`).join("\n")}\n}\nreturn Definition{},false\n}\n`,
);
write(
  "src/apps/web/src/auth/result.gen.ts",
  `// Code generated by scripts/generate-catalogs.mjs. DO NOT EDIT.\nexport const resultCodes = {\n${codes.map((c) => `${c.name}: ${JSON.stringify(c.code)},`).join("\n")}\n} as const;\nexport type ResultCode = typeof resultCodes[keyof typeof resultCodes];\nexport const resultStatuses: Record<ResultCode, number> = ${JSON.stringify(Object.fromEntries(codes.map((c) => [c.code, c.status])))};\n`,
);
const catalog = JSON.parse(readFileSync("src/apps/iam/internal/authorization/permissions.json", "utf8"));
const permissionKeys = new Set();
for (const permission of catalog) {
  assert(!permissionKeys.has(permission.key), `Duplicate permission ${permission.key}`);
  permissionKeys.add(permission.key);
  assert(["platform", "organization"].includes(permission.scope));
  assert(!(permission.scope === "platform" && permission.delegable));
}
const name = (key) =>
  key
    .split(".")
    .map((part) =>
      part === "iam"
        ? "IAM"
        : part
            .split("_")
            .map((word) => word[0].toUpperCase() + word.slice(1))
            .join(""),
    )
    .join("");
const permissionNames = new Set();
for (const permission of catalog) {
  const exportName = name(permission.key);
  assert(!permissionNames.has(exportName), `Duplicate permission export name ${exportName}`);
  permissionNames.add(exportName);
}
write(
  "src/packages/go/iamclient/permissions.gen.go",
  "// Code generated by scripts/generate-catalogs.mjs. DO NOT EDIT.\npackage iamclient\n\nconst (\n" +
    catalog.map((permission) => `Permission${name(permission.key)} = ${JSON.stringify(permission.key)}`).join("\n") +
    "\n)\n",
);
write(
  "src/apps/web/src/auth/permissions.gen.ts",
  "// Code generated by scripts/generate-catalogs.mjs. DO NOT EDIT.\nexport const permissions = {\n" +
    catalog.map((permission) => `  ${name(permission.key)}: ${JSON.stringify(permission.key)},`).join("\n") +
    "\n} as const;\nexport type PermissionKey = typeof permissions[keyof typeof permissions];\n",
);

const directory = mkdtempSync(path.join(tmpdir(), "spx-catalogs-"));
const manifest = "src/packages/generated-catalogs.json";
try {
  for (const [filename, content] of outputs) {
    const staged = path.join(directory, filename);
    mkdirSync(path.dirname(staged), { recursive: true });
    writeFileSync(staged, content);
  }
  const goFiles = [...outputs.keys()]
    .filter((filename) => filename.endsWith(".go"))
    .map((filename) => path.join(directory, filename));
  const formatted = spawnSync("gofmt", ["-w", ...goFiles], { stdio: "inherit" });
  if (formatted.status !== 0) throw new Error("Cannot format business catalog exports");
  for (const filename of outputs.keys()) outputs.set(filename, readFileSync(path.join(directory, filename)));
  const previous = existsSync(manifest) ? JSON.parse(readFileSync(manifest, "utf8")) : [];
  const extra = extraGeneratedFiles(outputs, previous);
  const manifestContent = JSON.stringify([...outputs.keys()].sort(), null, 2) + "\n";
  if (process.argv.includes("--check")) {
    const changed = [...outputs]
      .filter(([filename, content]) => !existsSync(filename) || !readFileSync(filename).equals(content))
      .map(([filename]) => filename);
    if (!existsSync(manifest) || readFileSync(manifest, "utf8") !== manifestContent) changed.push(manifest);
    if (changed.length || extra.length)
      throw new Error("Business catalog exports differ: " + [...changed, ...extra].join(", "));
    console.log(`Business catalog exports verified: ${outputs.size} files.`);
  } else {
    for (const filename of extra) rmSync(filename, { force: true });
    for (const [filename, content] of outputs) {
      mkdirSync(path.dirname(filename), { recursive: true });
      writeFileSync(filename, content);
    }
    writeFileSync(manifest, manifestContent);
  }
} finally {
  rmSync(directory, { recursive: true, force: true });
}
