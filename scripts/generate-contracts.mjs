import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const sharedPath = 'src/contracts/common/';
const toolchain = /^toolchain (\S+)$/m.exec(readFileSync('go.mod', 'utf8'))?.[1];
if (!toolchain) throw new Error('Pin the Go toolchain before generating contracts');
const codes = JSON.parse(readFileSync(`${sharedPath}error-codes.json`, 'utf8'));
const shared = JSON.parse(readFileSync(`${sharedPath}openapi.json`, 'utf8'));
if (JSON.stringify(shared.components.schemas.Result.required) !== JSON.stringify(['code', 'message', 'data', 'request_id'])) throw new Error('Update Result generators when changing its wire fields');
const outputs = new Map();
const write = (filename, content) => outputs.set(filename, content);
write(`${sharedPath}codes.gen.go`, `// Code generated by scripts/generate-contracts.mjs. DO NOT EDIT.\npackage common\n\n// Code 是跨语言契约中的稳定结果码。\ntype Code string\n\n// Definition 记录结果码对应的 HTTP 状态与默认公开消息。\ntype Definition struct { Status int; Message string }\n\nconst (\n${codes.map(c => `Code${c.name} Code = ${JSON.stringify(c.code)}`).join('\n')}\n)\n\n// Lookup 查询已注册结果码；未知码不会被当作成功。\nfunc Lookup(code Code) (Definition, bool) {\nswitch code {\n${codes.map(c => `case Code${c.name}: return Definition{Status:${c.status},Message:${JSON.stringify(c.message)}},true`).join('\n')}\n}\nreturn Definition{},false\n}\n`);
write(`${sharedPath}result.gen.go`, `// Code generated by scripts/generate-contracts.mjs. DO NOT EDIT.\npackage common\n\n// Result 是普通 JSON API 的统一结果，data 的业务类型由具体接口确定。\ntype Result[T any] struct {\nCode Code \x60json:"code"\x60\nMessage string \x60json:"message"\x60\nData T \x60json:"data"\x60\nRequestID string \x60json:"request_id"\x60\n}\n`);
write('src/apps/web/src/auth/result.gen.ts', `// Code generated by scripts/generate-contracts.mjs. DO NOT EDIT.\nexport const resultCodes = {\n${codes.map(c=>`${c.name}: ${JSON.stringify(c.code)},`).join('\n')}\n} as const;\nexport type ResultCode = typeof resultCodes[keyof typeof resultCodes];\nexport type Result<T> = { code: ResultCode; message: string; data: T; request_id: string };\nexport const resultStatuses: Record<ResultCode, number> = ${JSON.stringify(Object.fromEntries(codes.map(c=>[c.code,c.status])))};\n`);
const catalog = JSON.parse(readFileSync('src/contracts/iam/permissions.json', 'utf8'));
const name = (key) => key.split('.').map((part) => part === 'iam' ? 'IAM' : part.split('_').map((word) => word[0].toUpperCase() + word.slice(1)).join('')).join('');
write('src/contracts/iam/permissions.gen.go', '// Code generated by scripts/generate-contracts.mjs. DO NOT EDIT.\npackage iam\n\nconst (\n' + catalog.map((permission) => `Permission${name(permission.key)} = ${JSON.stringify(permission.key)}`).join('\n') + '\n)\n');
write('src/apps/web/src/auth/permissions.gen.ts', '// Code generated by scripts/generate-contracts.mjs. DO NOT EDIT.\nexport const permissions = {\n' + catalog.map((permission) => `  ${name(permission.key)}: ${JSON.stringify(permission.key)},`).join('\n') + '\n} as const;\nexport type PermissionKey = typeof permissions[keyof typeof permissions];\n');

write(`${sharedPath}error-codes.openapi.gen.json`, JSON.stringify({
  openapi: '3.0.3', info: { title: 'SecPlexus result codes', version: '1.0.0' }, paths: {},
  components: { schemas: { ErrorCode: { type: 'string', enum: codes.filter(c => c.code !== 'ok').map(c => c.code) } } },
}, null, 2) + '\n');
const directory = mkdtempSync(path.join(tmpdir(), 'spx-contracts-'));
const stagedContracts = path.join(directory, 'contracts');
const stagedWeb = path.join(directory, 'web');
const goFiles = [];
function run(command, args, env = process.env) {
  const result = spawnSync(command, args, { stdio: 'inherit', env });
  if (result.error || result.status !== 0) throw new Error(`Contract generation failed: ${command}`);
}
function generate(input, config, destination) {
  const filename = path.join(directory, `${goFiles.length}.json`);
  const output = path.join(directory, `${goFiles.length}.gen.go`);
  writeFileSync(filename, JSON.stringify({ ...config, output }));
  run('go', ['run', 'github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.1', '-config', filename, input], { ...process.env, GOTOOLCHAIN: toolchain });
  goFiles.push([destination, output]);
}
function collect(directory, destination) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const source = path.join(directory, entry.name);
    const target = `${destination}/${entry.name}`;
    if (entry.isDirectory()) collect(source, target);
    else outputs.set(target, readFileSync(source));
  }
}
try {
  cpSync('src/contracts', stagedContracts, { recursive: true });
  writeFileSync(path.join(stagedContracts, 'common/error-codes.openapi.gen.json'), outputs.get(`${sharedPath}error-codes.openapi.gen.json`));
  for (const module of ['iam', 'console']) {
    const source = path.join(stagedContracts, module);
    for (const name of ['schemas', 'openapi', ...(module === 'iam' ? ['internal'] : [])]) {
      const output = path.join(source, `${name}.json`);
      run('pnpm', ['exec', 'redocly', 'bundle', path.join(source, `${name}.source.json`), ...(name === 'schemas' ? [] : ['--remove-unused-components']), '-o', output, '--ext', 'json'], { ...process.env, REDOCLY_TELEMETRY: 'off' });
      outputs.set(`src/contracts/${module}/${name}.json`, readFileSync(output));
    }
    generate(path.join(source, 'schemas.json'), {
      package: module, generate: { models: true }, 'output-options': { 'skip-prune': true }, 'allow-remote-refs-from': [],
    }, `src/contracts/${module}/api.gen.go`);
    const config = JSON.parse(readFileSync(`src/contracts/${module}/gin.config.json`, 'utf8'));
    generate(path.join(source, 'openapi.source.json'), config, config.output);
    if (module === 'iam') {
      const config = JSON.parse(readFileSync('src/contracts/iam/internal-gin.config.json', 'utf8'));
      generate(path.join(source, 'internal.source.json'), config, config.output);
      const client = JSON.parse(readFileSync('src/contracts/iam/client.config.json', 'utf8'));
      generate(path.join(source, 'internal.source.json'), client, client.output);
    }
  }
  run('pnpm', ['--dir', 'src/apps/web', 'exec', 'openapi-ts', '--no-log-file'], {
    ...process.env, SPX_CONTRACT_INPUT: stagedContracts, SPX_CONTRACT_OUTPUT: stagedWeb,
  });
  for (const [destination, source] of goFiles) outputs.set(destination, readFileSync(source));
  collect(stagedWeb, 'src/apps/web/src/spx/api');
  const manifest = 'src/contracts/generated-files.json';
  const previous = existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')) : [];
  const formatted = path.join(directory, 'formatted');
  for (const [filename, content] of outputs) {
    const staged = path.join(formatted, filename);
    mkdirSync(path.dirname(staged), { recursive: true });
    writeFileSync(staged, content);
  }
  run('gofmt', ['-w', ...[...outputs.keys()].filter(filename => filename.endsWith('.go')).map(filename => path.join(formatted, filename))]);
  for (const filename of outputs.keys()) outputs.set(filename, readFileSync(path.join(formatted, filename)));
  const manifestContent = JSON.stringify([...outputs.keys()].sort(), null, 2) + '\n';
  const obsolete = ['src/apps/web/src/auth/api.gen.ts', 'src/apps/web/src/auth/console-api.gen.ts'];
  if (process.argv.includes('--check')) {
    const stale = [...outputs].filter(([filename, content]) => !existsSync(filename) || !readFileSync(filename).equals(content)).map(([filename]) => filename);
    stale.push(...previous.filter(filename => !outputs.has(filename) && existsSync(filename)), ...obsolete.filter(filename => existsSync(filename)));
    if (!existsSync(manifest) || readFileSync(manifest, 'utf8') !== manifestContent) stale.push(manifest);
    if (stale.length) throw new Error(`Generated contracts differ; run pnpm contracts:generate: ${stale.join(', ')}`);
    console.log(`Generated file set and contents verified: ${outputs.size} files.`);
  } else {
    for (const filename of previous) if (!outputs.has(filename)) rmSync(filename, { force: true });
    for (const filename of obsolete) rmSync(filename, { force: true });
    for (const [filename, content] of outputs) {
      mkdirSync(path.dirname(filename), { recursive: true });
      writeFileSync(filename, content);
    }
    writeFileSync(manifest, manifestContent);
  }

} finally {
  rmSync(directory, { recursive: true, force: true });
}
