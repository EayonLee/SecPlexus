package config

import "github.com/spf13/viper"

// bindEnvironment 显式登记模块字段及环境优先级；默认值仅在 config.yaml 定义。
func bindEnvironment(v *viper.Viper) {

	_ = v.BindEnv("app.name", "SPX_IAM_NAME")
	_ = v.BindEnv("app.host", "SPX_IAM_HOST")
	_ = v.BindEnv("app.port", "SPX_IAM_PORT")
	_ = v.BindEnv("app.public_url", "SPX_PUBLIC_URL")
	_ = v.BindEnv("app.trusted_proxy_cidrs", "SPX_IAM_TRUSTED_PROXY_CIDRS")
	_ = v.BindEnv("db.host", "SPX_IAM_POSTGRES_HOST", "SPX_POSTGRES_HOST")
	_ = v.BindEnv("db.port", "SPX_IAM_POSTGRES_PORT", "SPX_POSTGRES_PORT")
	_ = v.BindEnv("db.name", "SPX_IAM_POSTGRES_DATABASE", "SPX_POSTGRES_DATABASE")
	_ = v.BindEnv("db.user", "SPX_IAM_POSTGRES_USER", "SPX_POSTGRES_USER")
	_ = v.BindEnv("db.password", "SPX_IAM_POSTGRES_PASSWORD", "SPX_POSTGRES_PASSWORD")
	_ = v.BindEnv("db.sslmode", "SPX_IAM_POSTGRES_MODELESS", "SPX_POSTGRES_MODELESS")
	_ = v.BindEnv("db.url", "SPX_IAM_POSTGRES_URL", "SPX_POSTGRES_URL")
	_ = v.BindEnv("cache.host", "SPX_IAM_REDIS_HOST", "SPX_REDIS_HOST")
	_ = v.BindEnv("cache.port", "SPX_IAM_REDIS_PORT", "SPX_REDIS_PORT")
	_ = v.BindEnv("cache.user", "SPX_IAM_REDIS_USER", "SPX_REDIS_USER")
	_ = v.BindEnv("cache.password", "SPX_IAM_REDIS_PASSWORD", "SPX_REDIS_PASSWORD")
	_ = v.BindEnv("cache.db", "SPX_IAM_REDIS_DB", "SPX_REDIS_DB")
	_ = v.BindEnv("cache.url", "SPX_IAM_REDIS_URL", "SPX_REDIS_URL")
	_ = v.BindEnv("internal.host", "SPX_IAM_INTERNAL_HOST")
	_ = v.BindEnv("internal.port", "SPX_IAM_INTERNAL_PORT")
	_ = v.BindEnv("internal.tls_cert_file", "SPX_IAM_TLS_CERT_FILE")
	_ = v.BindEnv("internal.tls_key_file", "SPX_IAM_TLS_KEY_FILE")
	_ = v.BindEnv("internal.clients.console.token", "SPX_CONSOLE_IAM_TOKEN")
	_ = v.BindEnv("auth.csrf_key", "SPX_IAM_CSRF_KEY")
	_ = v.BindEnv("auth.session_idle_timeout", "SPX_IAM_SESSION_IDLE_TIMEOUT")
	_ = v.BindEnv("auth.session_absolute_timeout", "SPX_IAM_SESSION_ABSOLUTE_TIMEOUT")
	_ = v.BindEnv("auth.reauth_window", "SPX_IAM_REAUTH_WINDOW")
	_ = v.BindEnv("auth.login_max_failures", "SPX_IAM_LOGIN_MAX_FAILURES")
	_ = v.BindEnv("auth.login_lock_duration", "SPX_IAM_LOGIN_LOCK_DURATION")
	_ = v.BindEnv("bootstrap.username", "SPX_IAM_BOOTSTRAP_USERNAME")
	_ = v.BindEnv("bootstrap.password", "SPX_IAM_BOOTSTRAP_PASSWORD")
	_ = v.BindEnv("retention.audit_days", "SPX_IAM_AUDIT_RETENTION_DAYS")
	_ = v.BindEnv("retention.session_days", "SPX_IAM_SESSION_RETENTION_DAYS")
	_ = v.BindEnv("logging.level", "SPX_IAM_LOG_LEVEL")
	_ = v.BindEnv("logging.stdout", "SPX_IAM_LOG_STDOUT")
	_ = v.BindEnv("logging.file", "SPX_IAM_LOG_FILE")
	_ = v.BindEnv("logging.max_size_mb", "SPX_IAM_LOG_MAX_SIZE_MB")
	_ = v.BindEnv("logging.max_backups", "SPX_IAM_LOG_MAX_BACKUPS")
	_ = v.BindEnv("logging.max_age_days", "SPX_IAM_LOG_MAX_AGE_DAYS")
	_ = v.BindEnv("logging.compress", "SPX_IAM_LOG_COMPRESS")
}
